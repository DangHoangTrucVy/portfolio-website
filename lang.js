function setLanguage(lang) {
  localStorage.setItem("lang", lang);

  const t = translations[lang];

  const setText = (id, text) => {
    const el = document.getElementById(id);
    if (el) el.innerText = text;
  };

  setText("navOverview", t.navOverview);
  setText("navSound", t.navSound);
  setText("navProducer", t.navProducer);
  setText("navPerf", t.navPerformance);

  setText("soundTitle", t.soundTitle);
  setText("soundDesc", t.soundDesc);

  setText("producerTitle", t.producerTitle);
  setText("producerDesc", t.producerDesc);

  setText("chooseSoundTitle", t.chooseSoundTitle);
  setText("chooseSoundDesc", t.chooseSoundDesc);
  setText("chooseProducerTitle", t.chooseProducerTitle);
  setText("chooseProducerDesc", t.chooseProducerDesc);

  setText("perfHeroTitle", t.perfTitle);
  setText("titleGameShows", t.gameShowsTitle);
  setText("titleLiveShows", t.liveShowsTitle);
  setText("titleJudging", t.judgingTitle);
  setText("roleJudge", t.judgeRole);

  document.querySelectorAll(".choose-card span").forEach((el) => {
    el.innerText = t.explore;
  });

  const statTexts = document.querySelectorAll(".stats .stat-item p");
  if (statTexts.length >= 4) {
    statTexts[0].innerText = t.statProjects;
    statTexts[1].innerText = t.statYears;
    statTexts[2].innerText = t.statArtists;
    statTexts[3].innerText = t.statAwards;
  }

  const quoteText = document.querySelector(".quote-content p");
  const quoteAuthor = document.querySelector(".quote-content small");
  if (quoteText) quoteText.innerText = t.quoteText;
  if (quoteAuthor) quoteAuthor.innerText = t.quoteAuthor;

  const whatTitle = document.querySelector(".what h2");
  if (whatTitle) whatTitle.innerText = t.whatTitle;

  const whatCards = document.querySelectorAll(".what-card");
  if (whatCards.length >= 3) {
    whatCards[0].querySelector("h3").innerText = t.liveSoundTitle;
    whatCards[0].querySelector("p").innerText = t.liveSoundDesc;

    whatCards[1].querySelector("h3").innerText = t.studioTitle;
    whatCards[1].querySelector("p").innerText = t.studioDesc;

    whatCards[2].querySelector("h3").innerText = t.postTitle;
    whatCards[2].querySelector("p").innerText = t.postDesc;
  }

  const processTitle = document.querySelector(".process h2");
  if (processTitle) processTitle.innerText = t.processTitle;

  const steps = document.querySelectorAll(".step");
  if (steps.length >= 4) {
    steps[0].querySelector("h4").innerText = t.step1Title;
    steps[0].querySelector("p").innerText = t.step1Desc;

    steps[1].querySelector("h4").innerText = t.step2Title;
    steps[1].querySelector("p").innerText = t.step2Desc;

    steps[2].querySelector("h4").innerText = t.step3Title;
    steps[2].querySelector("p").innerText = t.step3Desc;

    steps[3].querySelector("h4").innerText = t.step4Title;
    steps[3].querySelector("p").innerText = t.step4Desc;
  }

  const featuredShows = document.querySelector(".sound-work > h2");
  if (featuredShows) featuredShows.innerText = t.featuredShows;

  const otherShows = document.querySelector(".other-shows h3");
  if (otherShows) otherShows.innerText = t.otherShows;

  const showToggle = document.getElementById("showToggle");
  if (showToggle) {
    const isOpen = document
      .querySelector(".show-list")
      ?.classList.contains("show-all");
    showToggle.innerText = isOpen ? t.showLess : t.showAll;
  }

  const createTitle = document.querySelector(".create h2");
  if (createTitle) createTitle.innerText = t.createTitle;

  const createCards = document.querySelectorAll(".create-card");
  if (createCards.length >= 3) {
    createCards[0].querySelector("h3").innerText = t.originalTitle;
    createCards[0].querySelector("p").innerText = t.originalDesc;

    createCards[1].querySelector("h3").innerText = t.beatTitle;
    createCards[1].querySelector("p").innerText = t.beatDesc;

    createCards[2].querySelector("h3").innerText = t.filmTitle;
    createCards[2].querySelector("p").innerText = t.filmDesc;
  }

  const collaborationsTitle = document.querySelector(".productions h2");
  if (collaborationsTitle)
    collaborationsTitle.innerText = t.collaborationsTitle;

  const footerDesc = document.querySelector(".footer-col:first-child p");
  if (footerDesc) footerDesc.innerText = t.footerDesc;

  const footerCols = document.querySelectorAll(".footer-col");
  if (footerCols.length >= 4) {
    footerCols[1].querySelector("h4").innerText = t.footerNavigation;
    footerCols[2].querySelector("h4").innerText = t.footerServices;
    footerCols[3].querySelector("h4").innerText = t.footerContact;

    const navLinks = footerCols[1].querySelectorAll("a");
    if (navLinks.length >= 4) {
      navLinks[0].innerText = t.navOverview;
      navLinks[1].innerText = t.navSound;
      navLinks[2].innerText = t.navProducer;
      navLinks[3].innerText = t.navPerformance;
    }

    const serviceLinks = footerCols[2].querySelectorAll("a");
    if (serviceLinks.length >= 4) {
      serviceLinks[0].innerText = t.footerLive;
      serviceLinks[1].innerText = t.footerStudio;
      serviceLinks[2].innerText = t.footerMix;
      serviceLinks[3].innerText = t.footerMusic;
    }

    const contactTexts = footerCols[3].querySelectorAll("p");
    if (contactTexts.length >= 3) {
      contactTexts[2].innerText = t.footerLocation;
    }
  }

  const footerBottom = document.querySelector(".footer-bottom p:last-child");
  if (footerBottom) footerBottom.innerText = t.footerBottom;

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.classList.remove("active");
    if (btn.innerText.toLowerCase() === lang) {
      btn.classList.add("active");
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("lang") || "en";
  setLanguage(savedLang);
});
